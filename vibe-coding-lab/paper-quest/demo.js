很多人把“学习”理解为反复阅读和划重点，但认知科学的大量研究表明，这类做法带来的往往是熟悉感，而不是可提取的长期记忆。本文梳理了三条最稳健的学习证据：间隔效应、提取练习与交错练习，并讨论“合意困难”为何能让学习更持久。在此基础上，本文提出一套面向文献阅读的闯关式流程：把长文切分为小关卡，每一关以主动回忆收尾，并用即时反馈维持动机。我们认为，把阅读从被动输入改造为主动提取，是对抗拖延与遗忘最有效的杠杆。

