早在十九世纪末，艾宾浩斯就通过自我实验描绘了遗忘曲线：新学习的内容在最初的几小时到几天内遗忘得最快，随后遗忘速度逐渐放缓。这意味着如果不进行任何复习，大部分细节会在一周内流失。
